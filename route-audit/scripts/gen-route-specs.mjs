#!/usr/bin/env node
/**
 * gen-route-specs.mjs
 *
 * Emit one Playwright spec per phase from routes.manifest.yaml.
 *
 *   node scripts/gen-route-specs.mjs --phase 2-themes
 *   node scripts/gen-route-specs.mjs --all
 *
 * Generated specs are a STARTING POINT, not the finished artifact. Hand-check
 * every one before committing: the generator cannot know that a selector is
 * ambiguous, that a page needs a wait, or that an assertion is asserting the
 * wrong thing. A generated spec nobody read is a green light nobody earned.
 *
 * Requires: yaml, @playwright/test
 */

import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";

const args = process.argv.slice(2);
const opt = (n, d) => {
  const i = args.indexOf(`--${n}`);
  return i === -1 ? d : args[i + 1];
};
const MANIFEST = opt("manifest", "routes.manifest.yaml");
const OUTDIR = opt("outdir", "e2e/routes");
const ONLY = opt("phase", null);
const ALL = args.includes("--all");

if (!ONLY && !ALL) {
  console.error("specify --phase <id> or --all");
  process.exit(1);
}

const manifest = YAML.parse(fs.readFileSync(MANIFEST, "utf8"));
const phases = new Map();
for (const r of manifest.routes ?? []) {
  if (ONLY && r.phase !== ONLY) continue;
  if (!phases.has(r.phase)) phases.set(r.phase, []);
  phases.get(r.phase).push(r);
}

const q = (s) => JSON.stringify(s);

function assertionsFor(route) {
  const lines = [];
  for (const a of route.must_render ?? []) {
    if (a.selector && a.min_count) {
      lines.push(
        `    await expect(page.locator(${q(a.selector)})).toHaveCount(${a.min_count}, { timeout: 10_000 });`,
      );
    } else if (a.selector) {
      lines.push(
        `    await expect(page.locator(${q(a.selector)}).first()).toBeVisible({ timeout: 10_000 });`,
      );
    } else if (a.text) {
      lines.push(
        `    await expect(page.getByText(${q(a.text)}, { exact: false }).first()).toBeVisible({ timeout: 10_000 });`,
      );
    }
  }
  for (const m of route.must_not ?? []) {
    if (typeof m === "object" && m.text) {
      lines.push(`    await expect(page.getByText(${q(m.text)}, { exact: false })).toHaveCount(0);`);
    }
  }
  if (!lines.length) {
    lines.push(
      `    // TODO: no must_render assertions authored for this route.`,
      `    // Body-visible only — this asserts almost nothing. Author the manifest entry.`,
      `    await expect(page.locator("body")).toBeVisible();`,
    );
  }
  return lines.join("\n");
}

function specFor(phase, routes) {
  const blocks = routes
    .flatMap((r) =>
      (r.fixtures?.length ? r.fixtures : [r.path]).map((url) => {
        if (url.includes("REPLACE-ME")) {
          return `  test.skip(${q(`${r.path} → ${url}`)}, async () => {
    // Fixture URL not yet supplied. Fill fixtures in routes.manifest.yaml.
    // A skipped test is honest; a test against an invented slug is not.
  });`;
        }
        const mustNot = r.must_not ?? [];
        const wantsConsole = mustNot.includes("console_errors");
        const wantsNetwork = mustNot.includes("network_failures");
        const isPlain =
          url.endsWith(".xml") || url.endsWith(".txt") || url.includes("sitemap");
        const navAssert = isPlain
          ? `    const response = await page.goto(${q(url)}, { waitUntil: "domcontentloaded" });
    expect(response?.status(), \`navigation status for ${url}\`).toBeLessThan(400);
    const body = await response!.text();
${(r.must_render ?? [])
  .filter((a) => a.text)
  .map(
    (a) =>
      `    expect(body.toLowerCase(), ${q(`body contains ${a.text}`)}).toContain(${q(String(a.text).toLowerCase())});`,
  )
  .join("\n")}`
          : `    const response = await page.goto(${q(url)}, { waitUntil: "domcontentloaded" });
    expect(response?.status(), \`navigation status for ${url}\`).toBeLessThan(400);

${assertionsFor(r)}`;

        return `  test(${q(url)}, async ({ page }) => {
    const consoleErrors: string[] = [];
    const failedRequests: string[] = [];
    page.on("console", (m) => {
      if (m.type() === "error") consoleErrors.push(m.text());
    });
    page.on("response", (res) => {
      if (res.status() >= 400) failedRequests.push(\`\${res.status()} \${res.url()}\`);
    });

${navAssert}

${wantsConsole ? `    expect(consoleErrors, "console errors").toEqual([]);` : ""}
${wantsNetwork ? `    expect(failedRequests, "failed requests").toEqual([]);` : ""}
  });`;
      }),
    )
    .join("\n\n");

  return `// GENERATED by scripts/gen-route-specs.mjs from ${MANIFEST}
// Phase: ${phase}
//
// Regenerating OVERWRITES this file. If you hand-edit an assertion, move the
// route's requirement into the manifest instead — the manifest is the contract,
// this file is its projection.

import { test, expect } from "@playwright/test";

test.describe(${q(`routes: ${phase}`)}, () => {
${blocks}
});
`;
}

fs.mkdirSync(OUTDIR, { recursive: true });
for (const [phase, routes] of phases) {
  const file = path.join(OUTDIR, `${phase}.spec.ts`);
  fs.writeFileSync(file, specFor(phase, routes));
  const skipped = routes.filter((r) =>
    (r.fixtures ?? []).some((f) => f.includes("REPLACE-ME")),
  ).length;
  const bare = routes.filter((r) => !(r.must_render?.length)).length;
  console.log(
    `wrote ${file}  (${routes.length} routes` +
      (skipped ? `, ${skipped} skipped for missing fixtures` : "") +
      (bare ? `, ${bare} with no real assertions` : "") +
      `)`,
  );
}

console.log(
  `\nNow READ the generated specs before committing. Assertion count is not assurance.`,
);
